#!/usr/bin/env python3
"""Generate `docs/documentation-index.md` from the tracked documentation tree.

The flat index is a view over the files, not a second place to maintain them:
its section totals and file lists come from `git ls-files`, so a new or renamed
document is one `--write` away and a stale index fails `--check`.

Usage:
    python scripts/docgen/doc_index.py --write   # regenerate
    python scripts/docgen/doc_index.py --check    # fail if the file is stale
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
OUTPUT = REPO_ROOT / "docs" / "documentation-index.md"

# Section directories in reading order, with the one-line purpose used in the
# hub table. A directory must be listed here to be indexed.
SECTIONS: tuple[tuple[str, str], ...] = (
    ("architecture", "System design, pipeline flow, data model"),
    ("api", "REST API reference and data models"),
    ("concepts", "Active Inference theory, agents, category theory"),
    ("guides", "Getting started, running, contributing"),
    ("operations", "Deployment, monitoring, logging, governance"),
    ("reference", "Configuration, language matrix, glossary, dependencies"),
    ("security", "Security architecture and cryptographic primitives"),
    ("systems", "P3IF, Cognitive Sovereignty, IC2S2, William Blake"),
    ("testing", "Testing strategy and verification methods"),
    ("tutorials", "First agent, pipeline, analysis, grants, benchmarking"),
)


def tracked_markdown() -> list[str]:
    out = subprocess.run(
        ["git", "ls-files", "-z", "--", "docs", "*.md"],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    return [p for p in out.split("\0") if p.endswith(".md")]


def section_files(section: str, files: list[str]) -> list[str]:
    prefix = f"docs/{section}/"
    return sorted(f[len(prefix) :] for f in files if f.startswith(prefix))


def render(files: list[str]) -> str:
    docs_files = [f for f in files if f.startswith("docs/")]
    root_docs = sorted(
        f[len("docs/") :]
        for f in docs_files
        if "/" not in f[len("docs/") :] and f != str(OUTPUT.relative_to(REPO_ROOT))
    )
    lines = [
        "# Documentation index",
        "",
        "> Generated by `scripts/docgen/doc_index.py` — do not edit by hand.",
        "> Regenerate with `python scripts/docgen/doc_index.py --write`; the",
        "> `docs` gate arm fails when this file is stale.",
        "",
        "Every long-lived document in [`docs/`](.) in one flat list, plus each",
        "section's own count. The narrative hub is [`README.md`](README.md);",
        "measured gate numbers (arm wall times, test counts) are in",
        "[`_generated/gate_metrics.md`](_generated/gate_metrics.md).",
        "",
        f"**{len(docs_files)} tracked Markdown files under `docs/`.**",
        "",
        "## Section totals",
        "",
        "| Section | Docs | Purpose |",
        "|---|---:|---|",
    ]
    total = 0
    for section, purpose in SECTIONS:
        count = len(section_files(section, files))
        total += count
        lines.append(f"| [`{section}/`]({section}/README.md) | {count} | {purpose} |")
    lines.append(
        f"| **Total in sections** | **{total}** | plus the hub, index, "
        "and generated pages below |"
    )
    lines += ["", "## Hub and generated pages", ""]
    for name in root_docs:
        lines.append(f"- [`{name}`]({name})")
    for name in ("_generated/gate_metrics.md",):
        if (REPO_ROOT / "docs" / name).exists():
            lines.append(f"- [`{name}`]({name})")
    lines.append("")
    for section, _purpose in SECTIONS:
        names = section_files(section, files)
        lines += [f"## {section}/", ""]
        for name in names:
            lines.append(f"- [`{name}`]({section}/{name})")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="regenerate the index")
    mode.add_argument("--check", action="store_true", help="fail if stale")
    args = parser.parse_args(argv)

    rendered = render(tracked_markdown())
    if args.write:
        OUTPUT.write_text(rendered, encoding="utf-8")
        print(f"wrote {OUTPUT.relative_to(REPO_ROOT)}")
        return 0

    current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
    if current != rendered:
        print(
            f"{OUTPUT.relative_to(REPO_ROOT)} is stale: run "
            "`python scripts/docgen/doc_index.py --write`",
            file=sys.stderr,
        )
        return 1
    print(f"{OUTPUT.relative_to(REPO_ROOT)} is current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
